import { readFileSync } from 'node:fs';
import { getDocument } from 'pdfjs-dist';
import { readDocx, readPdf, xray } from './src/index.ts';
const file = process.argv[2] as string;
const data = new Uint8Array(readFileSync(file));
const read = file.endsWith('.pdf') ? await readPdf(data, getDocument) : readDocx(data);
const result = xray(read);
console.log(result.summary.text, '| fonts', read.fonts.join(', '));
for (const check of result.checks) if (check.status !== 'pass') console.log(`[${check.status}] ${check.name}: ${check.summary}${check.examples ? ' | ' + check.examples.join(' / ') : ''}`);
console.log('sections:', result.sections.map((s) => `${s.title}→${s.kind}`).join(', '));
const f = result.fields;
console.log('name:', f.name, '@', f.nameLine, '| email:', f.email, '| phone:', f.phone, '| location:', f.location, '| links:', f.links.join(', '));
for (const job of f.jobs) console.log('job:', job.title, '|', job.company, '|', job.location, '|', job.dates.text);
for (const s of f.education) console.log('school:', s.degree, '|', s.school, '|', s.dates);
console.log('skills:', f.skills.join(', '));
if (process.argv[3]) console.log(read.lines.map((l) => `${l.look.padEnd(32)} ${l.text}`).join('\n'));
